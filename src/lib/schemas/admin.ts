import { z } from "zod";
import { PASSWORD_MAX, PASSWORD_MIN } from "@/lib/auth/policy.mjs";
import { OsSchema, SlugSchema, StatusSchema } from "@/lib/schemas";

/* Every string has an upper bound so a single request can't store unbounded data.
 * Format rules mirror the CHECK constraints documented in docs/DB.README.md. */

const text = (max: number) => z.string().trim().min(1).max(max);
const IdSchema = z.number().int().positive().max(2_147_483_647);

/* ---------- auth ---------- */

export const EmailSchema = z
  .string()
  .trim()
  .toLowerCase()
  .max(254)
  .regex(/^[^@\s]+@[^@\s]+\.[^@\s]+$/, "must be an email address");

export const PasswordSchema = z.string().min(PASSWORD_MIN).max(PASSWORD_MAX);

export const LoginBodySchema = z
  .object({
    email: EmailSchema,
    // Login accepts any length up to the max, so the policy change can't lock anyone out.
    password: z.string().min(1).max(PASSWORD_MAX),
  })
  .strict()
  .meta({ id: "AdminLogin" });
export type LoginBody = z.infer<typeof LoginBodySchema>;

export const ChangePasswordBodySchema = z
  .object({
    current_password: z.string().min(1).max(PASSWORD_MAX),
    new_password: PasswordSchema,
  })
  .strict()
  .refine((b) => b.current_password !== b.new_password, {
    message: "must differ from the current password",
    path: ["new_password"],
  })
  .meta({ id: "AdminChangePassword" });

export const AdminSchema = z
  .object({ id: z.uuid(), email: z.string(), display_name: z.string().nullable() })
  .meta({ id: "Admin" });
export type Admin = z.infer<typeof AdminSchema>;

export const SessionResponseSchema = z
  .object({ admin: AdminSchema, csrf_token: z.string() })
  .meta({ id: "AdminSession" });

/* ---------- apps ---------- */

export const PackageInputSchema = z
  .object({
    package_manager_id: IdSchema,
    package_name: z
      .string()
      .trim()
      .min(1)
      .max(200)
      .regex(/^[A-Za-z0-9@._+/:-]+$/, "letters, digits and @ . _ + / : - only"),
    command_override: text(300).nullable().default(null),
  })
  .strict();

const unique = <T>(items: T[]) => new Set(items).size === items.length;

export const AppInputSchema = z
  .object({
    slug: SlugSchema,
    name: text(100),
    tagline: text(200),
    about: text(5000),
    category_id: IdSchema,
    language_id: IdSchema.nullable(),
    status: StatusSchema,
    github_owner: z
      .string()
      .trim()
      .max(39)
      .regex(/^[A-Za-z0-9][A-Za-z0-9-]*$/, "must be a GitHub user or organisation name"),
    github_repo: z
      .string()
      .trim()
      .max(100)
      .regex(/^[A-Za-z0-9._-]+$/, "must be a GitHub repository name"),
    is_published: z.boolean(),
    features: z.array(text(300)).max(30),
    /** Terminal transcript lines. Lines starting with "$ " are shown as prompts (generated column is_prompt). */
    demo: z.array(z.string().max(300)).max(50),
    os: z.array(OsSchema).max(3).refine(unique, "must not repeat an OS"),
    license_ids: z.array(IdSchema).max(10).refine(unique, "must not repeat a license"),
    packages: z
      .array(PackageInputSchema)
      .max(30)
      .refine((p) => unique(p.map((x) => x.package_manager_id)), "one entry per package manager"),
  })
  .strict()
  .meta({ id: "AdminAppInput" });
export type AppInput = z.infer<typeof AppInputSchema>;

export const AppUpdateSchema = AppInputSchema.extend({
  /** updated_at as last read by the client; the update is refused if the row changed since. */
  expected_updated_at: z.iso.datetime(),
})
  .strict()
  .meta({ id: "AdminAppUpdate" });
export type AppUpdate = z.infer<typeof AppUpdateSchema>;

export const AppIdParamsSchema = z.object({ id: z.uuid() });

export const AdminAppRowSchema = z
  .object({
    id: z.uuid(),
    slug: z.string(),
    name: z.string(),
    status: StatusSchema,
    category: z.string(),
    is_published: z.boolean(),
    updated_at: z.string(),
  })
  .meta({ id: "AdminAppRow" });
export type AdminAppRow = z.infer<typeof AdminAppRowSchema>;

export const AdminAppSchema = AppInputSchema.extend({
  id: z.uuid(),
  /** Generated by the database from github_owner and github_repo. */
  github_url: z.string().nullable(),
  created_at: z.string(),
  updated_at: z.string(),
})
  .strict()
  .meta({ id: "AdminApp" });
export type AdminApp = z.infer<typeof AdminAppSchema>;

const LookupSchema = z.object({ id: z.number().int(), name: z.string() });

export const LookupsSchema = z
  .object({
    categories: z.array(LookupSchema),
    languages: z.array(LookupSchema),
    licenses: z.array(LookupSchema.extend({ spdx_id: z.string() })),
    package_managers: z.array(LookupSchema.extend({ slug: z.string(), command_template: z.string() })),
  })
  .meta({ id: "AdminLookups" });
export type Lookups = z.infer<typeof LookupsSchema>;
